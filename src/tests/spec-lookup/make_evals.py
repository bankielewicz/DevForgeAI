def prompt_md(description, tags, limits, prompt):
    return (f'---\ndescription: "{description}"\ntags: [{", ".join(tags)}]\nmax_turns: {limits[0]}\n'
            f"timeout_seconds: {limits[1]}\nallowed_tools: {TOOLS}\n---\n{prompt}\n")


def case_yaml(name, scaffold):
    text = f'schema_version: "1.1"\nname: {name}\n'
    return text + ("context:\n  scaffold_script: scaffold.sh\n" if scaffold else "")


def all_cases():
    cases = []
    for c in CASES:
        ver_tag = "ver-" + c["ver"].split("-")[1]
        cases.append({"name": c["name"], "ver": c["ver"], "fixture": c["fixture"], "premise": c["premise"],
                      "prompt.md": prompt_md(c["description"], ["spec-lookup", ver_tag], CASE_LIMITS, c["prompt"]),
                      "graders": c["graders"]})
    for name, positive, prompt in TRIGGERS:
        kind = "positive" if positive else "negative"
        description = f"VER-06 ({kind}): the skill {'fires' if positive else 'does not fire'}."
        grader = (tool_used("ver06-skill-fired", "Skill", SKILL_MATCH, minimum=1, arm="both") if positive else
                  tool_used("ver06-skill-not-fired", "Skill", SKILL_MATCH, minimum=0, maximum=0, arm="both"))
        cases.append({"name": name, "ver": "VER-06", "fixture": True, "premise": [],
                      "prompt.md": prompt_md(description, ["trigger", "ver-06", "spec-lookup-trigger"], SHORT_LIMITS, prompt),
                      "graders": [grader]})
    return cases


# The trigger cases are named trigger-NN, as VER-06 says, and so are context's; their extra tag spec-lookup-trigger
# selects exactly these five (--tag spec-lookup-trigger), since --case 'trigger-*' would match both suites.

# --------------------------------------------------------------------------------------------------------
# Premise checks, then writing


def check_premise(case):
    """Run the case's scaffold in a temporary folder, then find_spec.py for each premise query."""
    with tempfile.TemporaryDirectory() as tmp:
        if case["fixture"]:
            script = Path(tmp) / "scaffold.sh"
            script.write_text(scaffold_script(case["ver"], case["name"], FIXTURE))
            subprocess.run(["bash", str(script)], cwd=tmp, check=True)
            script.unlink()
        for query, code, expected in case["premise"]:
            proc = subprocess.run([sys.executable, "-S", "-B", str(FIND_SPEC), query], cwd=tmp,
                                  capture_output=True, text=True)
            if proc.returncode != code or expected not in proc.stdout:
                sys.exit(f"{case['name']}: premise failed for {query!r} (exit {proc.returncode}):\n{proc.stdout}")


def main():
    cases = all_cases()
    for case in cases:
        check_premise(case)
    if OUT.exists():
        shutil.rmtree(OUT)
    for case in cases:
        folder = OUT / case["name"]
        (folder / "graders").mkdir(parents=True)
        (folder / "case.yaml").write_text(case_yaml(case["name"], case["fixture"]))
        (folder / "prompt.md").write_text(case["prompt.md"])
        if case["fixture"]:
            script = folder / "scaffold.sh"
            script.write_text(scaffold_script(case["ver"], case["name"], FIXTURE))
            script.chmod(0o755)
        for name, body in case["graders"]:
            (folder / "graders" / f"{name}.md").write_text(body)
    print(f"wrote {len(cases)} cases under {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
