def scaffold_script(ver, case, files):
    lines = ["#!/usr/bin/env bash",
             f"# Seeds the fixtures for SPEC-014 {ver} ({case}). Generated by src/tests/spec-lookup/make_evals.py; "
             "edit the generator, not this file.",
             "set -euo pipefail"]
    for folder in sorted({str(Path(p).parent) for p in files}):
        lines.append(f"mkdir -p {folder}")
    for path, content in files.items():
        lines += [f"cat > {path} <<'SPECLOOKUPFIXTURE'", content.rstrip("\n"), "SPECLOOKUPFIXTURE"]
    return "\n".join(lines) + "\n"


